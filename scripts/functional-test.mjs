import assert from 'node:assert/strict';
import { closeCurriculum, closeReward, finish, openCurriculum, openQaPage, runOnly, runTests, switchMode } from './qa-helpers.mjs';
const qa = await openQaPage(); const { page } = qa;
await runTests(page, 'def say_hello(target: str = "PyOdyssey") -> str:\n    return f"Hello, {target}!"\n\nprint("Hello, PyOdyssey!")');
await page.getByTestId('tests-tab-button').click();
assert.ok(await page.locator('[data-testid="test-result-row"][data-status="passed"]').count() > 0);
assert.equal(await page.getByTestId('solved-badge').innerText(), 'Solved');
await closeReward(page);
await page.getByTestId('output-tab-button').click(); assert.match(await page.getByTestId('tests-panel-body').innerText(), /Hello, PyOdyssey!/);
await switchMode(page, 'sandbox'); await openCurriculum(page); await page.getByTestId('sandbox-example-recursion').click(); await closeCurriculum(page);
await runOnly(page, 'def countdown(n):\n    if n <= 0: return "LIFTOFF"\n    return countdown(n - 1)\nprint(countdown(3))');
assert.match(await page.getByTestId('tests-panel-body').innerText(), /LIFTOFF/); console.log('FUNCTIONAL PASS'); await finish(qa);
